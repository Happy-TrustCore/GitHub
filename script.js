function initContactForm() {
  const form = document.getElementById("projectForm");
  if (!form) return;

  form.addEventListener("submit", (e) => {
    e.preventDefault();

    const name = document.getElementById("name")?.value.trim();
    const email = document.getElementById("email")?.value.trim();
    const service =
      document.getElementById("serviceType")?.value || "Not selected";
    const message = document.getElementById("message")?.value.trim();

    const emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

    if (!name || !email || !message) {
      alert(t("formErrorEmpty"));
      return;
    }

    if (!emailPattern.test(email)) {
      alert(t("formErrorEmail"));
      return;
    }

    if (typeof emailjs === "undefined") {
      alert(
        "Email service failed to load. Please check your connection and try again, or contact us directly."
      );
      return;
    }

    const serviceID = "service_dhcp5pb";
    const templateID = "template_5aacjfg";

    const templateParams = {
      name: name,
      email: email,
      service: service,
      message: message,
    };

    emailjs
      .send(serviceID, templateID, templateParams)
      .then(() => {
        alert(t("formSuccess"));
        form.reset();
      })
      .catch((error) => {
        console.error("EmailJS Error:", error);
        const reason =
          (error && (error.text || error.message)) || "Unknown error";
        alert(`Email sending failed: ${reason}. Please try again.`);
      });
  });
}
