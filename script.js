/* AI CHATBOT (canned replies) */
/* ========================= */

function initChatbot() {
  const chatButton = document.getElementById("chatButton");
  const chatWindow = document.getElementById("chatWindow");
  const closeChat = document.getElementById("closeChat");
  const chatMessages = document.getElementById("chatMessages");
  const userMessageInput = document.getElementById("userMessage");
  const sendMessageBtn = document.getElementById("sendMessage");
  const startLeadBtn = document.getElementById("chatStartLead");

  if (!chatButton || !chatWindow) return;

  const emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  const leadTriggerPattern =
    /(start a project|start my project|hire|want to work|sign me up|get started|let's start|beauftragen|projekt starten|loslegen)/i;

  // Lead-capture state machine: null | "name" | "email" | "type" | "message"
  let leadStep = null;
  let leadData = {};

  function addMessage(text, sender) {
    const bubble = document.createElement("div");
    bubble.className = sender === "user" ? "user-message" : "bot-message";
    bubble.textContent = text;
    chatMessages.appendChild(bubble);
    chatMessages.scrollTop = chatMessages.scrollHeight;
  }

  function botReply(text) {
    setTimeout(() => addMessage(text, "bot"), 400);
  }

  chatButton.addEventListener("click", () => {
    const isOpen = chatWindow.style.display === "flex";
    chatWindow.style.display = isOpen ? "none" : "flex";
    if (!isOpen) userMessageInput.focus();
  });

  closeChat?.addEventListener("click", () => {
    chatWindow.style.display = "none";
  });

  function getBotReply(input) {
    const text = input.toLowerCase();

    if (/(service|offer|leistung|anbiet)/.test(text)) {
      return t("botServices");
    }
    if (/(price|cost|quote|budget|preis|kosten)/.test(text)) {
      return t("botPricing");
    }
    if (/(portfolio|project|work|example|projekt|arbeit)/.test(text)) {
      return t("botPortfolio");
    }
    if (/(contact|email|reach|talk|kontakt|erreich)/.test(text)) {
      return t("botContact");
    }
    if (/(hi|hello|hey|hallo)/.test(text)) {
      return t("botHello");
    }

    return t("botDefault");
  }

  function startLeadFlow() {
    leadStep = "name";
    leadData = {};
    botReply(t("chatLeadAskName"));
  }

  function handleLeadStep(text) {
    if (leadStep === "name") {
      leadData.name = text;
      leadStep = "email";
      botReply(t("chatLeadAskEmail").replace("{name}", leadData.name));
      return;
    }

    if (leadStep === "email") {
      if (!emailPattern.test(text)) {
        botReply(t("chatLeadInvalidEmail"));
        return;
      }
      leadData.email = text;
      leadStep = "type";
      botReply(t("chatLeadAskType"));
      return;
    }

    if (leadStep === "type") {
      leadData.projectType = /(free|student|portfolio|kostenlos)/i.test(text)
        ? "free"
        : "paid";
      leadStep = "message";
      botReply(t("chatLeadAskMessage"));
      return;
    }

    if (leadStep === "message") {
      leadData.message = text;
      leadStep = null;
      fillContactForm(leadData);
      botReply(t("chatLeadDone"));
    }
  }

  function sendMessage() {
    const text = userMessageInput.value.trim();
    if (!text) return;

    addMessage(text, "user");
    userMessageInput.value = "";

    if (leadStep) {
      handleLeadStep(text);
      return;
    }

    if (leadTriggerPattern.test(text)) {
      startLeadFlow();
      return;
    }

    botReply(getBotReply(text));
  }

  startLeadBtn?.addEventListener("click", () => {
    addMessage(startLeadBtn.textContent.trim(), "user");
    startLeadFlow();
  });

  sendMessageBtn?.addEventListener("click", sendMessage);
  userMessageInput?.addEventListener("keydown", (e) => {
    if (e.key === "Enter") sendMessage();
  });
}

